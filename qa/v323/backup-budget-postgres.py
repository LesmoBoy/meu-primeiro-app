#!/usr/bin/env python3
"""Compare browser-budget bytes with an isolated, disposable PostgreSQL 17.

Only synthetic fixture JSON is submitted. No app schema, accounts, credentials,
production connection, network port or persisted Docker volume is used.
"""
import json
import pathlib
import subprocess
import time
import uuid

ROOT = pathlib.Path(__file__).resolve().parents[2]
RESULT = pathlib.Path(__file__).with_name('backup-budget-postgres-result.json')


def command(arguments, **kwargs):
    return subprocess.run(arguments, text=True, check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          timeout=60, **kwargs)


def run():
    # Preserve the exact JS transport token for floating point values: Python
    # must not reserialize it and introduce e.g. an artificial ".0" scale.
    source = """const {load,fixtures}=require('./qa/v323/backup-budget-test.cjs');
const budget=load();process.stdout.write(JSON.stringify(fixtures().map(item=>({
  label:item.label,wire:JSON.stringify(item.value),budget:budget.inspect(item.value)
}))));"""
    fixtures = json.loads(command(['node', '-e', source], cwd=ROOT).stdout)
    name = 'rodagem-v323-budget-' + uuid.uuid4().hex[:12]
    cases = []
    try:
        command(['docker', 'run', '-d', '--rm', '--network', 'none', '--name', name,
                 '-e', 'POSTGRES_HOST_AUTH_METHOD=trust', 'postgres:17-alpine'])
        deadline = time.monotonic() + 40
        while True:
            ready = subprocess.run(['docker', 'exec', name, 'pg_isready', '-h',
                                    '127.0.0.1', '-U', 'postgres'],
                                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                   timeout=10)
            if ready.returncode == 0:
                break
            if time.monotonic() >= deadline:
                raise RuntimeError('Disposable PostgreSQL did not become ready')
            time.sleep(.25)
        version = command(['docker', 'exec', name, 'psql', '-qAt', '-U', 'postgres',
                           '-c', 'show server_version;']).stdout.strip()
        for fixture in fixtures:
            wire = fixture['wire']
            sql = "set standard_conforming_strings=on;\nselect octet_length('" + wire.replace("'", "''") + "'::jsonb::text);\n"
            actual = int(command(['docker', 'exec', '-i', name, 'psql', '-qAt',
                                  '-v', 'ON_ERROR_STOP=1', '-U', 'postgres'], input=sql).stdout.strip())
            budget = fixture['budget']
            assert budget['complete'], fixture['label']
            assert budget['wireBytes'] == len(wire.encode('utf-8')), fixture['label']
            assert budget['serverBytesUpperBound'] >= actual, fixture['label']
            cases.append({'label': fixture['label'], 'wireBytes': budget['wireBytes'],
                          'serverBytesUpperBound': budget['serverBytesUpperBound'],
                          'postgresJsonbTextBytes': actual,
                          'upperBoundMarginBytes': budget['serverBytesUpperBound'] - actual,
                          'fits': budget['fits']})
        large = next(case for case in cases if case['label'] == 'large-synthetic-snapshot')
        assert large['wireBytes'] < 5242880 < large['postgresJsonbTextBytes']
        assert large['fits'] is False
        report = {'classification': 'automated_local_postgresql', 'syntheticOnly': True,
                  'postgresVersion': version, 'isolatedNetwork': True,
                  'persistedVolume': False, 'passed': len(cases), 'errors': [], 'cases': cases}
        RESULT.write_text(json.dumps(report, indent=2, ensure_ascii=False) + '\n')
        print('BACKUP_BUDGET_POSTGRES_REPORT ' + json.dumps(report, ensure_ascii=False))
    finally:
        # This name is generated by this process; no unrelated instance is touched.
        subprocess.run(['docker', 'rm', '-f', name], stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL, timeout=15)


if __name__ == '__main__':
    run()
